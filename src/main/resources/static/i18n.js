/* ============================================================
   Рантайм i18n: разрешение языка, подстановка, перерисовка.
   ============================================================ */
function i18nResolve(){
  var s=null; try{ s=localStorage.getItem('lang'); }catch(e){}
  if(s&&I18N[s]) return s;
  var n=((navigator.language||navigator.userLanguage||'')+'').slice(0,2).toLowerCase();
  if(I18N[n]) return n;
  return 'ru';
}
var LANG=i18nResolve();

/* Индекс формы множественного числа по текущему языку. */
function i18nPlural(n){
  switch(LANG){
    case 'ru':{ var a=n%10,b=n%100; if(a===1&&b!==11)return 0; if(a>=2&&a<=4&&(b<10||b>=20))return 1; return 2; }
    case 'zh': return 0;
    default: return n===1?0:1; // en, es, hi
  }
}

/* Перевод с подстановкой %1, %2 … */
function t(key){
  var dict=I18N[LANG]||I18N.ru;
  var s=dict[key];
  if(s==null) s=I18N.en[key];
  if(s==null) return key;
  for(var i=1;i<arguments.length;i++){ s=s.split('%'+i).join(String(arguments[i])); }
  return s;
}
/* Форменные помощники. */
function i18nNapWord(n){ return (I18N[LANG]||I18N.ru)._nap[i18nPlural(n)]; }
function i18nYearWord(n){ return (I18N[LANG]||I18N.ru)._year[i18nPlural(n)]; }
function i18nMonthWord(n){ return (I18N[LANG]||I18N.ru)._month[i18nPlural(n)]; }
function i18nOrdNom(i){ var a=(I18N[LANG]||I18N.ru)._ordNom; return a[i]||String(i+1); }

/* Применить переводы к статической разметке (data-i18n*). */
function applyI18n(){
  document.documentElement.lang=LANG;
  document.title=t('brand_title');
  document.querySelectorAll('[data-i18n]').forEach(function(el){ el.textContent=t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-html]').forEach(function(el){ el.innerHTML=t(el.getAttribute('data-i18n-html')); });
  document.querySelectorAll('[data-i18n-ph]').forEach(function(el){ el.setAttribute('placeholder',t(el.getAttribute('data-i18n-ph'))); });
  document.querySelectorAll('[data-i18n-tip]').forEach(function(el){ var v=t(el.getAttribute('data-i18n-tip')); el.setAttribute('data-tip',v); el.setAttribute('aria-label',v); });
  document.querySelectorAll('[data-i18n-title]').forEach(function(el){ el.setAttribute('title',t(el.getAttribute('data-i18n-title'))); });
  document.querySelectorAll('.lang-select').forEach(function(sel){ sel.value=LANG; });
}

/* Заполнить выпадающие списки выбора языка. */
function buildLangSelects(){
  var opts=I18N_LANGS.map(function(l){ return '<option value="'+l.code+'">'+l.label+'</option>'; }).join('');
  document.querySelectorAll('.lang-select').forEach(function(sel){ sel.innerHTML=opts; sel.value=LANG; });
}

/* Сменить язык: запомнить, перерисовать статику и динамику. */
function setLang(code){
  if(!I18N[code]) code='ru';
  LANG=code;
  try{ localStorage.setItem('lang',code); }catch(e){}
  applyI18n();
  if(typeof onLangChange==='function') onLangChange();
}

